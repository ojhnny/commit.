// Builds the plugin into dist/commit-habits: main.js, styles.css, manifest.json.
import { execFileSync } from 'node:child_process'
import { mkdirSync, readFileSync, writeFileSync, copyFileSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import esbuild from 'esbuild'
import postcss from 'postcss'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const out = resolve(root, process.env.OUT_DIR ?? 'dist/commit-habits')
const production = !process.argv.includes('--dev')
mkdirSync(out, { recursive: true })

// ---------------------------------------------------------------- JavaScript
const builtins = ['electron', '@codemirror/autocomplete', '@codemirror/collab', '@codemirror/commands', '@codemirror/language',
  '@codemirror/lint', '@codemirror/search', '@codemirror/state', '@codemirror/view', '@lezer/common', '@lezer/highlight', '@lezer/lr']
await esbuild.build({
  entryPoints: [resolve(root, process.env.ENTRY ?? 'src/obsidian/main.ts')],
  bundle: true,
  format: process.env.ENTRY ? 'esm' : 'cjs',
  platform: 'browser',
  target: 'es2021',
  external: ['obsidian', ...builtins],
  outfile: resolve(out, process.env.ENTRY ? 'harness.js' : 'main.js'),
  minify: production,
  sourcemap: production ? false : 'inline',
  define: { 'process.env.NODE_ENV': JSON.stringify(production ? 'production' : 'development') },
  alias: { '@': resolve(root, 'src') },
  jsx: 'automatic',
  legalComments: 'none',
  logLevel: 'warning',
})

// ---------------------------------------------------------------- CSS
const raw = resolve(out, '.tw.css')
execFileSync(resolve(root, 'node_modules/.bin/tailwindcss'), ['-i', resolve(root, 'src/styles/plugin.css'), '-o', raw], { stdio: 'inherit', cwd: root })

// Every rule is scoped to .commit-root. `:not(#commit-scope)` lifts specificity above
// Obsidian's and themes' element styles (buttons, inputs) without !important.
const SCOPE = '.commit-root:not(#commit-scope)'
const ROOT_SELECTORS = new Set([':root', ':host', 'html', 'body'])
const px = (v) => v.replace(/(-?\d*\.?\d+)rem\b/g, (_, n) => `${+(parseFloat(n) * 16).toFixed(4)}px`)

const scope = () => ({
  postcssPlugin: 'commit-scope',
  Once(css) {
    // 1. Flatten cascade layers: unlayered host CSS would otherwise beat every layered rule.
    css.walkAtRules('layer', (at) => {
      if (at.nodes) at.replaceWith(at.nodes)
      else at.remove()
    })
    // 2. Width breakpoints follow the pane (container), not the window.
    css.walkAtRules('media', (at) => {
      if (/\bwidth\b/.test(at.params) && !/pointer|prefers/.test(at.params)) {
        at.name = 'container'
        at.params = `commit ${at.params}`
      }
    })
    // 3. Scope selectors.
    css.walkRules((rule) => {
      if (rule.parent?.type === 'atrule' && /keyframes$/.test(rule.parent.name)) return
      rule.selectors = rule.selectors.map((sel) => {
        const s = sel.trim()
        if (ROOT_SELECTORS.has(s)) return SCOPE
        if (s.startsWith('html') || s.startsWith(':root')) return SCOPE + s.replace(/^(html|:root)/, '')
        return `${SCOPE} ${s}`
      })
    })
    css.walkDecls((d) => {
      d.value = px(d.value)
    })
    css.walkAtRules((at) => {
      if (at.name === 'container' || at.name === 'media') at.params = px(at.params)
    })
  },
})

const tw = readFileSync(raw, 'utf8')
const host = readFileSync(resolve(root, 'src/styles/host.css'), 'utf8').replaceAll('SCOPE', SCOPE)
const font = readFileSync(resolve(root, 'node_modules/@fontsource-variable/geist/files/geist-latin-wght-normal.woff2')).toString('base64')
const fontFace = `@font-face{font-family:'Geist Variable';font-style:normal;font-display:swap;font-weight:100 900;src:url(data:font/woff2;base64,${font}) format('woff2-variations');}\n`
const result = await postcss([scope()]).process(tw, { from: undefined })
writeFileSync(resolve(out, 'styles.css'), `/* commit. — generated by scripts/build.mjs */\n${fontFace}${result.css}\n${host}`)

copyFileSync(resolve(root, 'manifest.json'), resolve(out, 'manifest.json'))
console.log(`Built ${out}`)
